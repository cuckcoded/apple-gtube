import Foundation

/// A minimal cookie jar with Netscape `cookies.txt` import/export.
///
/// The same file is handed to yt-dlp (playback, downloads), so the format must
/// stay compatible with what yt-dlp reads.
public struct Cookie: Sendable, Equatable {
    public var domain: String
    public var includeSubdomains: Bool
    public var path: String
    public var secure: Bool
    public var httpOnly: Bool
    public var expires: Int64
    public var name: String
    public var value: String

    public init(domain: String, includeSubdomains: Bool, path: String, secure: Bool, httpOnly: Bool, expires: Int64, name: String, value: String) {
        self.domain = domain
        self.includeSubdomains = includeSubdomains
        self.path = path
        self.secure = secure
        self.httpOnly = httpOnly
        self.expires = expires
        self.name = name
        self.value = value
    }
}

public func nowSecs() -> Int64 { Int64(Date().timeIntervalSince1970) }

public struct CookieJar: Sendable {
    public private(set) var cookies: [Cookie] = []

    public init(cookies: [Cookie] = []) { self.cookies = cookies }

    public static func parseNetscape(_ text: String) -> CookieJar {
        var out: [Cookie] = []
        for raw in text.split(omittingEmptySubsequences: false, whereSeparator: { $0 == "\n" }) {
            var line = String(raw)
            if line.hasSuffix("\r") { line.removeLast() }
            var httpOnly = false
            if line.hasPrefix("#HttpOnly_") {
                line = String(line.dropFirst("#HttpOnly_".count))
                httpOnly = true
            } else if line.hasPrefix("#") || line.trimmingCharacters(in: .whitespaces).isEmpty {
                continue
            }
            let parts = line.split(separator: "\t", omittingEmptySubsequences: false).map(String.init)
            if parts.count < 7 { continue }
            out.append(Cookie(
                domain: parts[0],
                includeSubdomains: parts[1].uppercased() == "TRUE",
                path: parts[2],
                secure: parts[3].uppercased() == "TRUE",
                httpOnly: httpOnly,
                expires: Int64(parts[4]) ?? 0,
                name: parts[5],
                value: parts[6...].joined(separator: "\t")
            ))
        }
        return CookieJar(cookies: out)
    }

    public func toNetscape() -> String {
        var out = "# Netscape HTTP Cookie File\n# Generated by GTube. Do not share this file.\n\n"
        for c in cookies {
            out += "\(c.httpOnly ? "#HttpOnly_" : "")\(c.domain)\t\(c.includeSubdomains ? "TRUE" : "FALSE")\t\(c.path)\t\(c.secure ? "TRUE" : "FALSE")\t\(c.expires)\t\(c.name)\t\(c.value)\n"
        }
        return out
    }

    public mutating func retain(_ keep: (Cookie) -> Bool) {
        cookies = cookies.filter(keep)
    }

    static func domainMatches(_ cookieDomain: String, _ host: String) -> Bool {
        var d = Substring(cookieDomain)
        while d.hasPrefix(".") { d = d.dropFirst() }
        return host == d || host.hasSuffix("." + d)
    }

    /// The value of a cookie that applies to `host`.
    public func get(_ host: String, _ name: String) -> String? {
        let now = nowSecs()
        return cookies.first { $0.name == name && Self.domainMatches($0.domain, host) && ($0.expires == 0 || $0.expires > now) }?.value
    }

    public mutating func set(_ domain: String, _ name: String, _ value: String) {
        cookies.removeAll { $0.name == name && $0.domain == domain }
        cookies.append(Cookie(domain: domain, includeSubdomains: domain.hasPrefix("."), path: "/", secure: true, httpOnly: false,
                              expires: nowSecs() + 3600 * 24 * 365, name: name, value: value))
    }

    /// The `Cookie:` header value for requests to `host`.
    public func header(for host: String) -> String {
        let now = nowSecs()
        var seen = Set<String>()
        var parts: [String] = []
        for c in cookies {
            if !Self.domainMatches(c.domain, host) || (c.expires != 0 && c.expires <= now) { continue }
            if seen.insert(c.name).inserted {
                parts.append("\(c.name)=\(c.value)")
            }
        }
        return parts.joined(separator: "; ")
    }

    public var hasLogin: Bool {
        get("www.youtube.com", "SAPISID") != nil || get("www.youtube.com", "__Secure-3PAPISID") != nil
    }

    /// Only what youtube.com needs; browsers export every site.
    public func onlyYouTube() -> CookieJar {
        var j = self
        j.retain { c in
            var d = Substring(c.domain)
            while d.hasPrefix(".") { d = d.dropFirst() }
            return d.hasSuffix("youtube.com")
        }
        return j
    }
}
